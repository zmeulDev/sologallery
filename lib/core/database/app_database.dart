/// The app's local SQLite database (Drift).
///
/// 100% on-device — no network, no cloud sync (Absolute rules). Schema is
/// versioned; every upgrade path is covered by a `SchemaVerifier` migration
/// test (see docs/spec.md#data-model and test/core/database/).
///
/// v1 holds only user-authored state that must exist before ML indexing:
/// favorites, albums + membership, and non-destructive edit instructions.
///
/// v2 adds the ML/indexing tables `photo_asset` (indexing cursor + lean cached
/// metadata) and `photo_label` (on-device ML Kit image labels).
///
/// v3 adds `photo_text` (on-device OCR) plus `persons` + `face_embedding`
/// (on-device face clustering / people).
///
/// v4 makes `photo_asset.indexed_at` nullable (NULL = metadata-swept, ML
/// pending) and adds `photo_asset.is_dated`, so the fast metadata sweep can
/// populate the grid before ML runs and undated assets route to "Older".
///
/// v5 adds `app_settings` (generic key/value prefs) — backs the Settings
/// screen's persisted theme override.
///
/// v6 adds `memories` + `memory_entry` — auto-curated memory collections
/// generated by the background indexer (docs/plans/memories-section.md).
///
/// v7 restores `face_embedding`'s box columns as normalized `[0, 1]` reals
/// instead of thumbnail pixels (see [FaceEmbeddings]). Stored pixel values
/// cannot be converted — the thumbnail dimensions they were measured against
/// were never recorded, which is the bug — so the faces are dropped and
/// re-derived (docs/plans/faces-first-run-and-avatar-crop.md).
///
/// v8 adds `persons.merged_into` — the user-asserted "same person" redirect
/// that survives the periodic global re-cluster (docs/plans/people-merge).
///
/// v9 adds a compound index on `photo_assets (is_dated, created_at)` — the
/// axis every Library query filters and ranges/sorts on. Before this the
/// hottest table had no secondary index, so background-ML `.watch()` re-runs
/// during a pass each full-scanned + filesorted. Pure index add, no data
/// change.
///
/// v10 adds `recently_viewed` — the Search screen's recently-viewed asset
/// ids. No foreign key, so it can record views before ML/indexing populates
/// `photo_asset`. Pure table add, no data change.
@DriftDatabase(
  tables: [
    Favorites,
    Albums,
    AlbumEntries,
    EditInstructions,
    PhotoAssets,
    PhotoLabels,
    PhotoTexts,
    Persons,
    FaceEmbeddings,
    AppSettings,
    Memories,
    MemoryEntries,
    RecentlyViewed,
  ],
  daos: [
    FavoritesDao,
    AlbumsDao,
    EditInstructionsDao,
    IndexDao,
    FacesDao,
    SettingsDao,
    MemoriesDao,
  ],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase([QueryExecutor? executor])
      : super(executor ?? _openConnection());

  @override
  int get schemaVersion => 10;

  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (m) async {
          await m.createAll();
        },
        onUpgrade: (m, from, to) async {
          if (from < 2) {
            // A fresh photo_assets is created from the *current* (v4) definition
            // — already nullable indexed_at + is_dated — so the v4 step below
            // must be skipped (else it would re-add is_dated).
            await m.createTable(photoAssets);
            await m.createTable(photoLabels);
            await m.create(photoLabelAsset);
            await m.create(photoLabelLabel);
          } else if (from < 4) {
            // Upgrading from v2/v3, where photo_assets has the old shape:
            // recreate it with the relaxed indexed_at nullability and the new
            // is_dated column, copying existing rows. Those rows were fully
            // ML-indexed, so indexed_at is preserved and is_dated defaults true.
            await m.alterTable(
              TableMigration(
                photoAssets,
                newColumns: [photoAssets.isDated],
              ),
            );
          }
          if (from < 3) {
            await m.createTable(photoTexts);
          }
          // persons arrives at v3 but gains merged_into at v8, so it needs the
          // same `else if` guard as photo_assets above: createTable builds the
          // *current* shape, so a from<3 run already has merged_into and must
          // not then run the v8 step (which would fail on a duplicate column).
          if (from < 3) {
            await m.createTable(persons);
          } else if (from < 8) {
            await m.addColumn(persons, persons.mergedInto);
          }
          // face_embedding arrives at v3 but its box columns change at v7, so
          // it needs the `else if` guard: createTable builds the *current*
          // shape, meaning a from<3 run already lands on v7 columns and must
          // not then run the v7 step (same trap as photo_assets above).
          if (from < 3) {
            await m.createTable(faceEmbeddings);
            await m.create(faceAsset);
            await m.create(facePerson);
          } else if (from < 7) {
            // Pixel boxes can't be rewritten as fractions — the dimensions
            // they were relative to are exactly what was never stored. Drop
            // the faces, drop the clusters built from them, and re-queue every
            // asset so the next pass re-derives both.
            await m.deleteTable(faceEmbeddings.actualTableName);
            await m.createTable(faceEmbeddings);
            await m.create(faceAsset);
            await m.create(facePerson);
            await customStatement('DELETE FROM ${persons.actualTableName}');
            await customStatement(
              'UPDATE ${photoAssets.actualTableName} SET indexed_at = NULL',
            );
          }
          if (from < 5) {
            await m.createTable(appSettings);
          }
          if (from < 6) {
            // Both tables are introduced at v6, so no `else if` guard is
            // needed — that trap only bites tables whose shape changes after
            // introduction (see photo_assets above).
            await m.createTable(memories);
            await m.createTable(memoryEntries);
            await m.create(memoryEntryMemory);
          }
          // v9: a compound index on photo_assets (is_dated, created_at) — the
          // axis every Library query filters and ranges/sorts on. Before this
          // the table had no secondary index at all, so every month/year/recent/
          // older/pending query full-scanned + filesorted, and a background ML
          // pass re-ran each visible Library `.watch()` stream per asset
          // stamped. One branch covers every upgrade path (v1→v9 … v8→v9):
          // the index didn't exist before v9, and fresh installs get it via
          // `onCreate`'s `createAll`.
          if (from < 9) {
            await m.create(photoAssetDatedCreated);
          }
          // v10: the Search screen's recently-viewed table. No `else if` guard
          // needed because this is the table's introduction; fresh installs get
          // it via `onCreate`/`createAll`.
          if (from < 10) {
            await m.createTable(recentlyViewed);
          }
        },
        beforeOpen: (details) async {
          // Foreign keys are OFF by default in SQLite; enable per-connection
          // so AlbumEntries cascade-on-album-delete (and photo_label cascade)
          // actually fire.
          await customStatement('PRAGMA foreign_keys = ON');
        },
      );

  static QueryExecutor _openConnection() {
    return driftDatabase(name: 'sologallery');
  }
}
